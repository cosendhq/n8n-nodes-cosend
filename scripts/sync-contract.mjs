#!/usr/bin/env node
/**
 * Regenerate `test/fixtures/contract.json` from cosend-api's generated contract.
 *
 * **Why the fixture exists at all.** This package publishes to npm with zero runtime
 * dependencies and eventually lives in its own public repo, so it cannot import cosend-api and
 * cannot depend on `@viciousxp/client` at runtime. The drift test therefore compares the node's
 * declared operations and the fields it sends against a checked-in fixture — and this script is
 * what makes that fixture *generated* rather than transcribed. Nobody types a path or a field name
 * by hand.
 *
 * **The input is `packages/contracts/generated/`, the artefacts A2 §10.1 names**: the operations
 * and their fields from `n8n-descriptions.ts`, the event catalogue from `openapi.json`. Both are
 * generated from the one route table and `pnpm contracts:check` fails the build when they lag it,
 * so reading them is reading the route table — through the published contract rather than around it.
 *
 * **Run it from inside the cosend-api monorepo, after `pnpm contracts`.** Once this package moves
 * to cosendhq/n8n-nodes-cosend the fixture is refreshed by running this script in a checkout of
 * cosend-api and copying the result across.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const generated = join(repo, 'packages', 'contracts', 'generated');

const { COSEND_OPERATIONS } = await import(
	pathToFileURL(join(generated, 'n8n-descriptions.ts')).href
);

/** A2 §10.2's `n8n:` marker. This subset IS the node's operation surface. */
const operations = COSEND_OPERATIONS.map((entry) => ({
	resource: entry.resource,
	operation: entry.operation,
	method: entry.method,
	// The node speaks to `{baseUrl}` which already ends in `/v1`, so the fixture stores the
	// path the node actually builds rather than the one the table declares.
	// Every `{param}` is `{id}`, as the drift test spells the node's `{{ $parameter.x }}`: the
	// node's parameter names (`conversationId`, `noteId`) are not the table's.
	path: entry.path.replace(/^\/v1/, '').replace(/\{[^}]+\}/g, '{id}'),
	idempotency: entry.idempotency,
	body: entry.body,
	query: entry.query,
})).sort((a, b) =>
	`${a.resource}.${a.operation}`.localeCompare(`${b.resource}.${b.operation}`, 'en'),
);

/**
 * A2 §7.2's closed event catalogue, read out of the request schema `openapi.json` publishes for
 * `POST /v1/webhook-endpoints` — so it is the same list the API refuses subscriptions against,
 * not a second copy of it.
 */
const openapi = JSON.parse(readFileSync(join(generated, 'openapi.json'), 'utf8'));
const events =
	openapi.paths?.['/v1/webhook-endpoints']?.post?.requestBody?.content?.['application/json']?.schema
		?.properties?.events?.items?.enum;
if (!Array.isArray(events) || events.length === 0) {
	throw new Error(
		'Could not read the event catalogue from POST /v1/webhook-endpoints in openapi.json.',
	);
}

/**
 * Which catalogue events something in cosend-api actually EMITS.
 *
 * The catalogue is closed and `POST /v1/webhook-endpoints` accepts a subscription to every name
 * in it — including any that no code path produces. Subscribing to one of those gives you a
 * trigger that can never fire: standing rule 9's dropdown-that-cannot-run, in its quietest form.
 *
 * Detection is a literal search for the event name across `src/`, minus the catalogue file that
 * declares it. Every producer in this codebase writes the name as a string literal — messaging
 * through its own `EVENT` map, notify, templates and connections inline — so a name appearing
 * nowhere but the catalogue has no producer. It is a heuristic, and it fails in the safe
 * direction: a producer built some other way shows up as a MISSING event and fails the node's
 * drift test loudly, rather than silently blessing an event that cannot fire.
 */
const CATALOGUE_FILE = join(repo, 'src', 'modules', 'webhooks', 'schema.ts');

function sourceFiles(directory) {
	const found = [];
	for (const entry of readdirSync(directory)) {
		const full = join(directory, entry);
		if (statSync(full).isDirectory()) found.push(...sourceFiles(full));
		else if (entry.endsWith('.ts') && full !== CATALOGUE_FILE) found.push(full);
	}
	return found;
}

const sources = sourceFiles(join(repo, 'src')).map((file) => readFileSync(file, 'utf8'));
const emitted = events.filter((event) => sources.some((source) => source.includes(`'${event}'`)));
const notEmitted = events.filter((event) => !emitted.includes(event));

const fixture = {
	_generated:
		'GENERATED by scripts/sync-contract.mjs from cosend-api/packages/contracts/generated. Do not edit by hand.',
	operations,
	events: [...events].sort(),
	/** Catalogue events with a producer in src/. These are the ones the trigger may offer. */
	eventsWithProducers: [...emitted].sort(),
	/** In the catalogue, accepted by the API, emitted by nothing. Offering one is rule-9 dead UI. */
	eventsWithoutProducers: [...notEmitted].sort(),
};

const out = join(here, '..', 'test', 'fixtures', 'contract.json');
writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
process.stdout.write(
	`Wrote ${operations.length} operations and ${events.length} events (${emitted.length} with producers, ${notEmitted.length} without) to ${out}\n`,
);
